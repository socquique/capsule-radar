#!/usr/bin/env python3
"""Generate src/st77916_ws185_init.h from Hermes Gadget SDK's panel_ws185.hpp.

Converts Waveshare's two ESP32-S3-Touch-LCD-1.85C ST77916 init tables (esp_lcd
{cmd, data, len, delay_ms} entries) into Arduino_GFX batchOperation() byte arrays,
keeping every command, its data and its delay unchanged. COLMOD 0x55 (RGB565) goes
first, where esp_lcd_st77916 sends it before the vendor table.

Usage:
    git -C ~/dev/hermes-gadget-sdk show origin/main:firmware/esp32/main/panel_ws185.hpp > /tmp/panel_ws185.hpp
    python3 tools/gen_st77916_init.py /tmp/panel_ws185.hpp src/st77916_ws185_init.h
"""
import re
import sys

ENTRY = re.compile(r'\{0x([0-9A-Fa-f]{2}), "([^"]*)", (\d+), (\d+)\}')
TABLES = {"kWs185PanelDefault": "ST77916_WS185_INIT_DEFAULT",
          "kWs185PanelNew": "ST77916_WS185_INIT_NEW"}


def parse(src, name):
    body = src.split(name + "[] = {")[1].split("};")[0]
    out = []
    for m in ENTRY.finditer(body):
        data = bytes.fromhex(m[2].replace("\\x", ""))[: int(m[3])]
        out.append((int(m[1], 16), data, int(m[4])))
    return out


def emit(entries):
    lines = ["    BEGIN_WRITE,", "    WRITE_C8_D8, 0x3A, 0x55,"]
    for cmd, data, delay in entries:
        lines.append("    WRITE_C8_BYTES, 0x%02X, %d,%s" % (
            cmd, len(data), "".join(" 0x%02X," % b for b in data)))
        if delay:
            lines.append("    END_WRITE, DELAY, %d, BEGIN_WRITE," % delay)
    lines.append("    END_WRITE,")
    return "\n".join(lines)


def main():
    src = open(sys.argv[1], encoding="utf-8").read()
    dst = sys.argv[2] if len(sys.argv) > 2 else "src/st77916_ws185_init.h"
    parts = [
        "// Auto-generated by tools/gen_st77916_init.py — DO NOT EDIT.",
        "// SPDX-FileCopyrightText: 2023 Espressif Systems (Shanghai) CO LTD",
        "// SPDX-License-Identifier: Apache-2.0",
        "// ST77916 init values from Waveshare's ESP32-S3-Touch-LCD-1.85C factory demo at",
        "// 8ead4a96bf3a278fc4ebd8ef4768657e17fa2880, as kept in Hermes Gadget SDK (MIT)",
        "// firmware/esp32/main/panel_ws185.hpp. Two panel revisions; the panel ID picks one.",
        "#pragma once",
        "#include <Arduino_GFX_Library.h>",
        "",
    ]
    for name, out in TABLES.items():
        parts.append("static const uint8_t %s[] = {\n%s\n};\n" % (out, emit(parse(src, name))))
    with open(dst, "w", encoding="utf-8") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
